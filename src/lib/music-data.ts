export const ALL_NOTES = [...WHITE_NOTES, ...BLACK_NOTES];

export const NOTE_BY_ID: Record<string, PianoNote> = Object.fromEntries(
  ALL_NOTES.map((note) => [note.id, note])
);

export function getNoteLabel(note: PianoNote | string, notation: NotationSystem = "deutsch"): string {
  const n = typeof note === "string" ? NOTE_BY_ID[note] : note;
  if (!n) return typeof note === "string" ? note : "";
  if (notation === "deutsch") return n.displayGerman;
  if (notation === "solfege") return n.displaySolfege;
  return n.display;
}

